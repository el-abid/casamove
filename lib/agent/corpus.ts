export function normalize(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export type LexicalHit = { doc: KnowledgeDoc; score: number };

export function lexicalRanking(
  query: string,
  locale: Locale,
  docs: KnowledgeDoc[] = corpus
): LexicalHit[] {
  const q = normalize(query);
  const tokens = Array.from(
    new Set(q.split(" ").filter((token) => token.length > 2))
  );

  const hits: LexicalHit[] = [];

  for (const doc of docs) {
    let score = 0;

    for (const keyword of new Set(doc.keywords)) {
      if (q.includes(normalize(keyword))) score += 2;
    }

    const haystack = normalize(`${doc.title[locale]} ${doc.body[locale]}`);
    const words = new Set(haystack.split(" ").filter(Boolean));
    for (const token of tokens) {
      if (words.has(token)) score += 1;
    }

    if (score > 0) hits.push({ doc, score });
  }

  return hits.sort((a, b) => b.score - a.score);
}

export function retrieve(
  query: string,
  locale: Locale,
  docs: KnowledgeDoc[] = corpus
): { doc: KnowledgeDoc; score: number } | null {
  const best = lexicalRanking(query, locale, docs)[0] ?? null;
  return best && best.score >= 3 ? best : null;
}

